#!/usr/bin/env bash
# Shared helpers - sourced by the other scripts (not meant to be run directly).

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
CONF_DIR="$ROOT/nginx/conf.d"
BACKUP_DIR="$ROOT/nginx/ssl-backup"      # original HTTP-only configs live here while SSL is enabled
CERTBOT_DIR="$ROOT/certbot"
ENV_FILE="$ROOT/config.env"
NGINX_CONTAINER="${NGINX_CONTAINER:-nginx-proxy}"
CERTBOT_IMAGE="${CERTBOT_IMAGE:-certbot/certbot:v3.0.1}"
CRON_MARK="# nginx-proxy-certbot:$ROOT"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warn]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

# Print the leading comment block of the calling script as help text
usage() { awk 'NR>1 && /^#/ {sub(/^# ?/,""); print; next} NR>1 {exit}' "$0"; }

require_docker() {
  command -v docker >/dev/null 2>&1 || die "docker not found (try: 1-install-nginx.sh --install-docker)"
  docker info >/dev/null 2>&1 || die "cannot reach the docker daemon (not running, or you are not in the 'docker' group - log out/in after install)"
  docker compose version >/dev/null 2>&1 || die "docker compose plugin not found"
}

nginx_running() {
  [[ "$(docker inspect -f '{{.State.Running}}' "$NGINX_CONTAINER" 2>/dev/null || true)" == "true" ]]
}
require_nginx() { nginx_running || die "container '$NGINX_CONTAINER' is not running (run 1-install-nginx.sh first)"; }

# Test config, then reload. Uses && so it also works inside `if ! nginx_reload`.
nginx_reload() {
  docker exec "$NGINX_CONTAINER" nginx -t && docker exec "$NGINX_CONTAINER" nginx -s reload
}

# Certbot runs as a throw-away container; no permanent certbot container needed.
run_certbot() {
  docker run --rm \
    -v "$CERTBOT_DIR/www:/var/www/certbot" \
    -v "$CERTBOT_DIR/conf:/etc/letsencrypt" \
    -v "$CERTBOT_DIR/logs:/var/log/letsencrypt" \
    "$CERTBOT_IMAGE" "$@"
}

# "app1", "app1.conf" or "nginx/conf.d/app1.conf" -> "app1"
norm_name() { local n="${1##*/}"; printf '%s' "${n%.conf}"; }

# Usable domain names from the first server_name line (skips _, wildcards, regexes)
server_names() {
  awk '/^[[:space:]]*server_name[[:space:]]/ {
         sub(/^[[:space:]]*server_name[[:space:]]+/, ""); sub(/;.*/, ""); print; exit }' "$1" \
    | tr -s ' \t' '\n' | grep -vE '^(_|\*.*|~.*|)$' || true
}

# stdin -> stdout, adds $1 right after the first server_name line
insert_after_server_name() {
  INSERT_TEXT="$1" awk '{ print } !done && /^[[:space:]]*server_name[[:space:]]/ { print ENVIRON["INSERT_TEXT"]; done=1 }'
}

# Prints a full SSL config generated from an HTTP-only config.
#   $1 = original http-only conf   $2 = certificate name (first domain)
build_ssl_conf() {
  local src="$1" primary="$2"
  local -a domains
  mapfile -t domains < <(server_names "$src")
  local ssl_lines="    http2 on;
    ssl_certificate     /etc/letsencrypt/live/$primary/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$primary/privkey.pem;"

  cat <<EOF
# ---- generated by 3-add-cert.sh: HTTP -> HTTPS redirect ----
# Original HTTP-only config is kept in nginx/ssl-backup/ and restored by 5-remove-cert.sh
server {
    listen 80;
    server_name ${domains[*]};

    location ^~ /.well-known/acme-challenge/ {
        root /var/www/certbot;
        try_files \$uri =404;
    }

    location / {
        return 301 https://\$host\$request_uri;
    }
}

# ---- HTTPS (your original server block, moved to 443) ----
EOF
  sed -E 's/^([[:space:]]*)listen[[:space:]]+(\[::\]:)?80([[:space:]]+default_server)?[[:space:]]*;/\1listen \2443 ssl\3;/' "$src" \
    | insert_after_server_name "$ssl_lines"
}

restore_http_config() {   # $1 = name ; returns 1 if that config was not SSL-enabled
  local bak="$BACKUP_DIR/$1.conf.http"
  [[ -f "$bak" ]] || return 1
  cp "$bak" "$CONF_DIR/$1.conf"
  rm -f "$bak"
}

install_cron() {
  command -v crontab >/dev/null 2>&1 || die "crontab not found (install cron, e.g. apt install cron)"
  local current line
  current="$(crontab -l 2>/dev/null || true)"
  line="0 3,15 * * * flock -n /tmp/certbot-renew.lock \"$SCRIPT_DIR/renew.sh\" >> \"$ROOT/certbot/logs/renew.log\" 2>&1 $CRON_MARK"
  { grep -vF "$CRON_MARK" <<<"$current" || true; echo "$line"; } | crontab -
}

remove_cron() {
  command -v crontab >/dev/null 2>&1 || return 0
  local current
  current="$(crontab -l 2>/dev/null || true)"
  if grep -qF "$CRON_MARK" <<<"$current"; then
    { grep -vF "$CRON_MARK" <<<"$current" || true; } | crontab -
    log "removed cron job"
  fi
}